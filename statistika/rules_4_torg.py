def _words(value: str) -> str:
    text = unicodedata.normalize("NFKC", value).casefold().replace("ё", "е")
    text = re.sub(r"\bд\s*[/\\]\s*", "для ", text)
    return " ".join(re.sub(r"[^\w%]+|_", " ", text).split())


