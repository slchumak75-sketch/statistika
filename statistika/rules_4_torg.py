def groups_for_4_torg(product_name: str, nomenclature_group: str) -> set[int]:
    name = re.sub(r"^\d{1,3} ", "", _words(product_name))
    section = _words(nomenclature_group)
    matches = set()
    alcohol = _alcohol(name, product_name)
    if alcohol is not None:
        matches.add(alcohol)
    if _WATER.match(name) and not _NOT_WATER.search(name):
        matches.add(45)
    if _TOBACCO.match(name) and not _NOT_TOBACCO.search(name):
        matches.add(46)
    if not _NOT_CONSTRUCTION.search(name) and (
        _CONSTRUCTION.match(name)
        or (section in _CONSTRUCTION_SECTIONS and _CONSTRUCTION_ITEM.match(name))
        or (_SANITARY_ITEM.match(name) and _SANITARY.search(name))
    ):
        matches.add(53)
    if not _NOT_CLEANER.match(name) and (
        _HOUSEHOLD.search(name) or _CLEANING_EXTRA.match(name)
        or (_HOUSEHOLD_CONTEXT.match(name) and _HOUSEHOLD_BRAND.search(name))
    ):
        matches.add(57)
    if not _NOT_COSMETIC.search(name) and (_COSMETIC.search(name) or _HYGIENE_PAD_BRAND.match(name)):
        matches.add(63)
    return matches
