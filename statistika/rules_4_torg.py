_LITRES = re.compile(r"\b\d+(?: \d+)?\s*л\b")


def _alcohol(name: str, original_name: str) -> int | None:
    if _NO_ALCOHOL.search(name) or _ZERO_PROOF.search(original_name):
        return None
    if _LOW_ALCOHOL.match(name):
        return 42
    if _WINE.match(name):
        if _FRUIT_WINE.search(name):
            return 36
        if _CARBONATED.search(name):  # Шипучее — не игристое; без уточнения не назначать.
            return None
        return 37 if _SPARKLING.search(name) else 35
    if re.match(r"^(?:советск\w+ )?шампанск\w*\b", name) and not _CARBONATED.search(name):
        return 37
    if re.match(r"^(?:водка|vodka)\b", name):
        return 43 if re.search(r"\b(?:виноградн\w*|чача|граппа)\b", name) else 38
    if _COGNAC.match(name):
        return 39
    if re.match(r"^(?:пиво|beer)\b", name):
        return 40
    if _LIQUEUR.match(name) and not re.search(r"\b(?:аптечн\w*|лекарств\w*|наружн\w*)\b", name):
        return 41
    if name.startswith("бальзам ") and _LITRES.search(name) and not re.search(r"\b(?:для|моющ\w*|волос\w*)\b", name):
        return 41
    if _SPIRITS.match(name):
        return 43
    return None


